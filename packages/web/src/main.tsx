import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import { QueryClient, QueryClientProvider } from '@tanstack/react-query';
import './styles.css';
import { App } from './App';
import { IconSprite } from './components/Icon';
import { agentModeEnabled } from './browserPreferences';
import { initialBrowserPreferences } from './hooks/useBrowserPreferences';
document.documentElement.dataset.agentMode = String(agentModeEnabled(location.search, initialBrowserPreferences().agentMode));
const queryClient = new QueryClient({ defaultOptions: { queries: { staleTime: 15_000, retry: 1 } } });
createRoot(document.getElementById('root')!).render(<StrictMode><IconSprite /><QueryClientProvider client={queryClient}><App /></QueryClientProvider></StrictMode>);
if('serviceWorker' in navigator&&import.meta.env.PROD)void navigator.serviceWorker.register('/sw.js');
